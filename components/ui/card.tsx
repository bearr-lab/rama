import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: "surface" | "elevated" | "highlight" }
>(({ className, variant = "surface", ...props }, ref) => {
  const variantStyles = {
    surface: "border border-border bg-surface-subtle",
    elevated: "border border-border bg-surface-subtle shadow-elevated",
    highlight: "border-l-4 border-l-fjord-500 border-y border-r border-y-stone-200 border-r-stone-200 bg-surface",
  }

  return (
    <div
      ref={ref}
      className={cn(
        "hover:shadow-elevated text-ink transition-all duration-300 hover:-translate-y-0.5",
        variantStyles[variant],
        className
      )}
      {...props}
    />
  )
})
Card.displayName = "Card"

